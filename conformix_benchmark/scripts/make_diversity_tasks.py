#!/usr/bin/env python3
"""Dev/test split and task list for the walk-jump exploration experiments.

Strategies are tuned on a development third of the ConforMix targets and then
evaluated, unchanged, on the remaining two thirds; tuning and reporting on the
same targets would overstate the gain. The split is stratified by subset and
fixed by hashing the target name, so it never depends on results.

Every strategy uses the baseline's settings (sigma = 2 A, delta = 2,
friction 0.1, seed generated by Boltz-2) and a matched budget of 1000 walk
steps per target. Diverse seeding spends that budget as 5 chains of 200 steps,
each with its own Boltz-2 seed.

Writes splits.csv and diversity_tasks_<split>.tsv; each task line is
    <config>  <out_dir>  <seed>  <extra boltz-jump arguments>

Usage:
    python scripts/make_diversity_tasks.py --split dev
    python scripts/make_diversity_tasks.py --split test --strategies baseline seed_h1_w2
"""

import argparse
import csv
import hashlib
import os
from pathlib import Path

from dotenv import find_dotenv, load_dotenv

HERE = Path(__file__).resolve().parent.parent
ROOT = HERE.parent
SUBSETS = ["crypticpockets", "domainmotion", "foldswitching", "membranetransporters"]
DEV_FRACTION = 1 / 3

BASE = "--walk_jump_sigma 2.0 --walk_jump_delta 2.0 --walk_jump_friction 0.1 --no_kernels --override"
# name -> (chains, steps per chain, extra arguments)
STRATEGIES = {
    "baseline": (1, 1000, ""),
    "diverse_seeds": (5, 200, ""),
    # Heights from a 30-step sweep on a 110-residue protein: <= 0.02 had no
    # measurable effect, 0.08 roughly doubled the distance travelled with an
    # intact backbone, and 0.5-2 broke the chain (consecutive C-alpha gaps of
    # 30+ A). Metadynamics accumulates hills, so it is bracketed more tightly.
    "seed_h0.08_w2": (1, 1000, "--diversity_mode seed --diversity_height 0.08 --diversity_width 2"),
    "seed_h0.15_w2": (1, 1000, "--diversity_mode seed --diversity_height 0.15 --diversity_width 2"),
    "metad_h0.04_w1.5": (1, 1000, "--diversity_mode metad --diversity_height 0.04 --diversity_width 1.5 "
                                  "--diversity_deposit_every 20 --diversity_bias_factor 10"),
    "metad_h0.08_w1.5": (1, 1000, "--diversity_mode metad --diversity_height 0.08 --diversity_width 1.5 "
                                  "--diversity_deposit_every 20 --diversity_bias_factor 10"),
}


def split_of(name):
    """Deterministic: the first third of hash space is dev."""
    h = int(hashlib.sha256(name.encode()).hexdigest()[:8], 16) / 0xFFFFFFFF
    return "dev" if h < DEV_FRACTION else "test"


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--split", choices=["dev", "test"], required=True)
    parser.add_argument("--strategies", nargs="+", default=list(STRATEGIES))
    args = parser.parse_args()
    load_dotenv(find_dotenv(usecwd=True), override=False)
    results = Path(os.environ["RESULTS_DIR"]) / "conformix_diversity"

    rows, tasks = [], []
    for subset in SUBSETS:
        for cfg in sorted((ROOT / "configs/conformix_benchmark" / subset).glob("*.yaml")):
            rows.append({"subset": subset, "target": cfg.stem, "split": split_of(cfg.stem)})
            if rows[-1]["split"] != args.split:
                continue
            for name in args.strategies:
                chains, steps, extra = STRATEGIES[name]
                for chain in range(chains):
                    out = results / name / subset / f"chain{chain}"
                    tasks.append(f"{cfg}\t{out}\t{chain}\t{BASE} --walk_jump_steps {steps} {extra}".rstrip() + "\n")

    with open(HERE / "splits.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=["subset", "target", "split"])
        w.writeheader()
        w.writerows(rows)
    out = HERE / f"diversity_tasks_{args.split}.tsv"
    out.write_text("".join(tasks))
    counts = {s: sum(r["split"] == "dev" and r["subset"] == s for r in rows) for s in SUBSETS}
    print(f"dev targets per subset: {counts} (total {sum(counts.values())} of {len(rows)})")
    print(f"{len(tasks)} runs for split={args.split} -> {out}")


if __name__ == "__main__":
    main()
